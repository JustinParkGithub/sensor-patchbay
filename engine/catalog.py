"""The module catalog: browse, download and remove sources/sinks from a remote index.

Sources and sinks no longer ship with the engine. They live in their own
repository (``sensor-patchbay-modules`` by default), which publishes an
``index.json`` beside the module folders::

    index.json
    sources/<type>/__init__.py, module.toml, ...
    sinks/<type>/...

The index is generated by that repo's ``tools/build_index.py``::

    {
      "format": 1,
      "modules": [
        {"name": "mock", "kind": "source", "description": "...", "version": "1.0.0",
         "entry": "__init__.py", "depends": ["joycon"], "python": [], "system": [],
         "digest": "<sha256 over the files>",
         "files": [{"path": "sources/mock/__init__.py", "sha256": "...", "size": 1234}, ...]}
      ]
    }

Every ``path`` is relative to the index's own URL, so any static host works:
``raw.githubusercontent.com``, GitHub Pages, a file server on the LAN, or a
local checkout (a plain path or ``file://`` URL — handy offline and for
developing modules).

Installing downloads each file, checks its sha256, and hands the result to
:func:`engine.library.install_upload` as a zip, so a catalog install goes
through exactly the same checks as an upload, and leaves the same install
record (``.install.json``, see :mod:`engine.modules`), naming the index as its
source. A module's ``depends`` are installed with it. The caller syncs
afterwards (:func:`engine.library.sync`).

Every installed module folder is listed, however it got there, in one of four
states (:func:`listing`):

* ``installed`` — unchanged since it was installed, and the catalog has nothing
  different (or no record, but the files match the catalog's exactly);
* ``update`` — unchanged locally, and the catalog's files differ. ``change``
  says whether the catalog's version is an ``upgrade``, a ``downgrade``, or the
  same version with different files (``changed``);
* ``modified`` — its files changed after it was installed;
* ``local`` — no install record: copied in by hand or loaded from ``--ext``.

Installing over a ``modified`` or ``local`` module would lose files nobody
installed, so :func:`install` refuses (:class:`Conflict`) unless ``force``.

Where the index comes from, first match wins:

1. ``PATCHBAY_CATALOG`` in the environment;
2. ``catalog = "..."`` in ``patchbay.toml``;
3. :data:`DEFAULT_URL`.

The last index fetched is cached in the data folder, so the catalog can still
be listed (not installed from) offline.
"""

from __future__ import annotations

import hashlib
import io
import json
import os
import re
import shutil
import threading
import time
import urllib.parse
import urllib.request
import zipfile
from pathlib import Path, PurePosixPath

from . import library, modules, paths

DEFAULT_URL = ("https://raw.githubusercontent.com/JustinParkGithub/"
               "sensor-patchbay-modules/main/index.json")
FORMAT = 1
TIMEOUT = 15                       # seconds per request
CACHE = paths.DATA / ".catalog-cache.json"
_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")

_lock = threading.Lock()
_memo: dict = {}                   # {"url":..., "index":..., "at": time}
MEMO_SECONDS = 300


class CatalogError(Exception):
    """Anything that should reach the user as a one-line message."""


class Conflict(CatalogError):
    """Installing would overwrite a modified or hand-placed module."""


# --------------------------------------------------------------------- location
def index_url() -> str:
    env = os.environ.get("PATCHBAY_CATALOG", "").strip()
    if env:
        return env
    url = str(modules.load_config().get("catalog", "") or "").strip()
    return url or DEFAULT_URL


def _as_url(location: str) -> str:
    """A URL, or a local path (absolute, ``~``, or relative to the data folder)."""
    if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*://", location):
        return location
    p = Path(location).expanduser()
    if not p.is_absolute():
        p = paths.DATA / p
    if p.is_dir():
        p = p / "index.json"
    return p.resolve().as_uri()


def _fetch(url: str, limit: int = library.MAX_UPLOAD) -> bytes:
    if urllib.parse.urlsplit(url).scheme not in ("https", "http", "file"):
        raise CatalogError(f"unsupported URL scheme: {url}")
    req = urllib.request.Request(url, headers={"User-Agent": "sensor-patchbay"})
    try:
        with urllib.request.urlopen(req, timeout=TIMEOUT) as res:
            data = res.read(limit + 1)
    except OSError as e:          # URLError, HTTPError, timeouts, missing files
        raise CatalogError(f"couldn't fetch {url}: {getattr(e, 'reason', e)}") from None
    if len(data) > limit:
        raise CatalogError(f"{url}: larger than {limit >> 20} MB")
    return data


# ------------------------------------------------------------------------ index
def _check_index(index) -> list[dict]:
    if not isinstance(index, dict) or not isinstance(index.get("modules"), list):
        raise CatalogError("not a module index (no \"modules\" list)")
    if index.get("format", 1) > FORMAT:
        raise CatalogError(f"index format {index['format']} is newer than this app "
                           f"understands ({FORMAT}); update sensor-patchbay")
    out = []
    for m in index["modules"]:
        if not isinstance(m, dict):
            continue
        name, kind = m.get("name"), m.get("kind")
        if not (isinstance(name, str) and _NAME.fullmatch(name)) or kind not in ("source", "sink"):
            continue
        prefix = PurePosixPath(f"{kind}s", name)
        files = []
        for f in m.get("files", []):
            rel = PurePosixPath(str(f.get("path", "")))
            if (rel.is_absolute() or ".." in rel.parts or rel.parts[:2] != prefix.parts
                    or len(rel.parts) < 3 or not isinstance(f.get("sha256"), str)):
                raise CatalogError(f"{name}: unsafe or malformed file entry {f.get('path')!r}")
            files.append({"path": str(rel), "sha256": f["sha256"].lower(),
                          "size": int(f.get("size", 0))})
        try:
            entry = modules.check_entry(m.get("entry", modules.DEFAULT_ENTRY))
        except ValueError as e:
            raise CatalogError(f"{name}: {e}") from None
        if f"{prefix}/{entry}" not in {f["path"] for f in files}:
            raise CatalogError(f"{name}: its entry {entry} isn't among its files")
        out.append({
            "name": name, "kind": kind,
            "description": str(m.get("description", "")),
            "version": str(m.get("version", "")),
            "entry": entry,
            "depends": [str(d) for d in m.get("depends", [])],
            "python": [str(p) for p in m.get("python", [])],
            "system": [str(s) for s in m.get("system", [])],
            "digest": str(m.get("digest", "")),
            "files": files,
        })
    return out


def fetch_index(refresh: bool = False) -> dict:
    """``{"url", "modules", "cached", "error"}``. Falls back to the on-disk cache
    (with ``cached: true`` and the reason in ``error``) when the fetch fails."""
    url = _as_url(index_url())
    with _lock:
        fresh = (_memo.get("url") == url and time.time() - _memo.get("at", 0) < MEMO_SECONDS)
        if fresh and not refresh:
            return {"url": url, "modules": _memo["modules"], "cached": False, "error": None}
        try:
            raw = _fetch(url)
            mods = _check_index(json.loads(raw))
        except (CatalogError, ValueError) as e:
            cached = _read_cache(url)
            if cached is None:
                raise CatalogError(str(e)) from None
            return {"url": url, "modules": cached, "cached": True, "error": str(e)}
        _memo.update(url=url, modules=mods, at=time.time())
        try:
            CACHE.parent.mkdir(parents=True, exist_ok=True)
            CACHE.write_text(json.dumps({"url": url, "modules": mods}))
        except OSError:
            pass
        return {"url": url, "modules": mods, "cached": False, "error": None}


def _read_cache(url: str) -> list[dict] | None:
    try:
        d = json.loads(CACHE.read_text())
        return d["modules"] if d.get("url") == url else None
    except (OSError, ValueError, KeyError):
        return None


# -------------------------------------------------------------------- installed
def installed() -> dict[str, modules.Module]:
    return {m.name: m for m in modules.find_modules(library.EXTRA_DIRS)}


def local_state(mod: modules.Module, entry: dict | None) -> dict:
    """Where an installed module stands, against its record and the catalog
    *entry* (None if the catalog doesn't have it). See the module docstring."""
    rec = modules.read_record(mod.path)
    current = modules.folder_digest(mod.path, mod.assets)
    out = {"installed_version": mod.version, "source": rec.get("source") if rec else None,
           "change": None}
    if rec is None:
        out["state"] = "installed" if entry and current == entry["digest"] else "local"
    elif current != rec["digest"]:
        out["state"] = "modified"
    elif entry and entry["digest"] != current:
        out["state"] = "update"
        cmp = modules.compare_versions(entry["version"], mod.version)
        out["change"] = {1: "upgrade", -1: "downgrade", 0: "changed"}.get(cmp, "changed")
    else:
        out["state"] = "installed"
    return out


def listing(refresh: bool = False) -> dict:
    """The catalog plus every installed module, each with its local state.

    Per module: the catalog's fields (``version`` is the catalog's), then
    ``state`` (``available`` when not installed; else see :func:`local_state`),
    ``installed_version``, ``change``, ``source`` (from the install record),
    ``runnable`` (this engine can run its entry) and ``removable`` (it lives
    in the data folder, so :func:`remove` may delete it).
    """
    idx = fetch_index(refresh)
    have = installed()
    out = []
    for m in idx["modules"]:
        local = have.pop(m["name"], None)
        row = {**{k: m[k] for k in ("name", "kind", "description", "version", "entry",
                                    "depends", "python", "system")},
               "size": sum(f["size"] for f in m["files"]),
               "runnable": m["entry"].endswith(".py")}
        if local is None:
            row.update(state="available", installed_version=None, change=None, source=None,
                       removable=False)
        else:
            row.update(local_state(local, m), removable=_removable(local))
        out.append(row)
    for local in have.values():
        out.append({"name": local.name, "kind": local.kind, "description": local.description,
                    "version": None, "entry": local.entry, "depends": local.depends,
                    "python": local.python, "system": local.system, "size": 0,
                    "runnable": local.python_entry, **local_state(local, None),
                    "removable": _removable(local)})
    out.sort(key=lambda m: (m["kind"], m["name"]))
    return {"url": idx["url"], "cached": idx["cached"], "error": idx["error"], "modules": out}


# ---------------------------------------------------------------------- install
def _closure(name: str, by_name: dict[str, dict]) -> list[str]:
    """*name* and everything it depends on, dependencies first."""
    order: list[str] = []
    seen: set[str] = set()

    def visit(n: str, chain: tuple[str, ...]):
        if n in chain:
            raise CatalogError(f"dependency cycle: {' -> '.join(chain + (n,))}")
        if n in seen:
            return
        if n not in by_name:
            raise CatalogError(f"{chain[-1] if chain else n}: needs {n!r}, which isn't in the catalog")
        for d in by_name[n]["depends"]:
            visit(d, chain + (n,))
        seen.add(n)
        order.append(n)

    visit(name, ())
    return order


def _download(entry: dict, base: str) -> bytes:
    """One module as a zip (``sources/<name>/...``), every file hash-checked."""
    buf = io.BytesIO()
    total = 0
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in entry["files"]:
            url = urllib.parse.urljoin(base, urllib.parse.quote(f["path"]))
            data = _fetch(url)
            if hashlib.sha256(data).hexdigest() != f["sha256"]:
                raise CatalogError(f"{entry['name']}: {f['path']} doesn't match the index "
                                   "(sha256 mismatch); the catalog may be mid-update, try again")
            total += len(data)
            if total > library.MAX_UNPACKED:
                raise CatalogError(f"{entry['name']}: larger than {library.MAX_UNPACKED >> 20} MB")
            zf.writestr(f["path"], data)
    return buf.getvalue()


def install(name: str, with_depends: bool = True, update: bool = True,
            force: bool = False) -> list[dict]:
    """Download *name* (and, unless told not to, whatever it ``depends`` on that
    isn't already installed) into the data folder. Returns one
    :func:`engine.library.install_upload` result per module written. Doesn't
    sync; call :func:`engine.library.sync` after.

    Raises :class:`Conflict` rather than overwrite a ``modified`` or ``local``
    copy of *name*, unless *force*."""
    idx = fetch_index()
    if idx["cached"]:
        raise CatalogError(f"catalog unreachable ({idx['error']})")
    by_name = {m["name"]: m for m in idx["modules"]}
    if name not in by_name:
        raise CatalogError(f"no module {name!r} in the catalog")
    have = installed()
    wanted = _closure(name, by_name) if with_depends else [name]
    results = []
    for n in wanted:
        if n != name and n in have:
            continue                       # a dependency that's already there stays as it is
        if n == name and n in have and not update:
            continue
        if n in have and not _removable(have[n]):
            raise CatalogError(f"{n} is loaded from {have[n].path}, outside the data folder; "
                               "remove it there first")
        if n in have and not force:
            state = local_state(have[n], by_name[n])["state"]
            if state in ("modified", "local"):
                raise Conflict(
                    f"{n} was changed after it was installed; installing would overwrite "
                    "those changes" if state == "modified" else
                    f"{n} wasn't installed from the catalog; installing would replace its files")
        data = _download(by_name[n], idx["url"])
        try:
            results.append(library.install_upload(f"{n}.zip", data, source=idx["url"]))
        except ValueError as e:
            raise CatalogError(str(e)) from None
    return results


# ----------------------------------------------------------------------- remove
def _removable(mod: modules.Module) -> bool:
    return not mod.external and mod.path.parent == paths.upload_dir(mod.kind)


def remove(name: str) -> dict:
    """Delete an installed module's folder from the data folder. Running
    instances keep running until removed; the next sync drops the type."""
    have = installed()
    mod = have.get(name)
    if mod is None:
        raise CatalogError(f"{name!r} isn't installed")
    if not _removable(mod):
        raise CatalogError(f"{name} lives in {mod.path}, not the data folder; remove it there")
    needed_by = sorted(m.name for m in have.values() if name in m.depends)
    shutil.rmtree(mod.path)
    return {"name": name, "kind": mod.kind, "needed_by": needed_by}
